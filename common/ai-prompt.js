/**
 * Builds user prompt containing the detected Google Forms questions and choices.
 * @param {Array<object>} questions - Filtered target questions (Radio and Checkbox)
 * @param {object} [formMetadata] - Title and description of form
 * @returns {string}
 */
export function buildUserPrompt(questions, formMetadata = {}) {
  const formTitle = formMetadata.title || 'Google Form';
  const formDesc = formMetadata.description || '';

  const formattedQuestions = questions.map(q => {
    const optionsList = (q.options || []).map(opt => {
      const otherTag = opt.isOther ? ' (Free-text Other option)' : '';
      return `      - id: "${opt.id}", label: "${opt.label}"${otherTag}`;
    }).join('\n');

    return [
      `Question ID: "${q.id}"`,
      `Index: ${q.index}`,
      `Type: ${q.type}`,
      `Required: ${q.required}`,
      `Prompt: "${q.title}"`,
      q.description ? `Help Text: "${q.description}"` : null,
      `Available Options:\n${optionsList}`
    ].filter(Boolean).join('\n');
  }).join('\n\n---\n\n');

  return [
    `FORM CONTEXT (Synthetic Survey UI Test):`,
    `Title: "${formTitle}"`,
    formDesc ? `Description: "${formDesc}"` : null,
    ``,
    `QUESTIONS TO ANALYZE (${questions.length} total):`,
    formattedQuestions,
    ``,
    `Return ONLY the JSON object with the "analysis" array covering all ${questions.length} questions.`
  ].filter(Boolean).join('\n');
}

/**
 * Extracts JSON from raw LLM text, handling <think> tags, markdown blocks, and truncated arrays.
 * @param {string} rawText
 * @returns {object|Array|null}
 */
function extractJsonPayload(rawText) {
  if (!rawText || typeof rawText !== 'string') return null;

  // Strip <think>...</think> blocks produced by reasoning models
  let text = rawText.replace(/<think>[\s\S]*?<\/think>/gi, '').trim();
  if (text.includes('<think>') && !text.includes('</think>')) {
    const afterThink = text.split('<think>').pop();
    const jsonStartInThink = afterThink.indexOf('{');
    if (jsonStartInThink !== -1) {
      text = afterThink.slice(jsonStartInThink);
    }
  }

  // Strip markdown code fences ```json ... ```
  const codeBlockMatch = text.match(/```(?:json)?\s*([\s\S]*?)\s*```/i);
  if (codeBlockMatch) {
    text = codeBlockMatch[1].trim();
  }

  // Try direct parse first
  try {
    return JSON.parse(text);
  } catch (_) {
    // Continue to substring and salvage strategies
  }

  // Try extracting outermost { ... }
  const firstBrace = text.indexOf('{');
  const lastBrace = text.lastIndexOf('}');
  if (firstBrace !== -1 && lastBrace > firstBrace) {
    const candidate = text.slice(firstBrace, lastBrace + 1);
    try {
      return JSON.parse(candidate);
    } catch (_) {
      // Fall through to truncated JSON salvage
    }
  }

  // Salvage truncated JSON: extract individual {"questionId": ...} objects
  const objectMatches = text.match(/\{[^{}]*"questionId"\s*:\s*"[^"]+"[^{}]*\}/g);
  if (objectMatches && objectMatches.length > 0) {
    const salvaged = [];
    for (const rawObj of objectMatches) {
      try {
        salvaged.push(JSON.parse(rawObj));
      } catch (_) {
        // Ignore malformed fragment
      }
    }
    if (salvaged.length > 0) {
      return { analysis: salvaged };
    }
  }

  return null;
}

/**
 * Extracts and parses JSON from raw LLM output text, validating schema and option IDs.
 * @param {string} rawResponse - Text response from OpenRouter
 * @param {Array<object>} originalQuestions - Original questions extracted from DOM
 * @returns {{ success: boolean, results: Array<object>, error?: string }}
 */
export function parseAndValidateAIResponse(rawResponse, originalQuestions = []) {
  if (!rawResponse || typeof rawResponse !== 'string' || !rawResponse.trim()) {
    return {
      success: false,
      results: [],
      error: 'Empty or invalid response received from AI model.'
    };
  }

  const parsedData = extractJsonPayload(rawResponse);
  if (!parsedData) {
    return {
      success: false,
      results: [],
      error: 'Failed to parse AI response as JSON.'
    };
  }

  let analysisItems = [];
  if (Array.isArray(parsedData)) {
    analysisItems = parsedData;
  } else if (parsedData && Array.isArray(parsedData.analysis)) {
    analysisItems = parsedData.analysis;
  } else if (parsedData && typeof parsedData === 'object') {
    // Support compact key-value map e.g. { "sfta_q_1": ["sfta_opt_0"] }
    for (const [k, v] of Object.entries(parsedData)) {
      if (k.startsWith('sfta_q_')) {
        analysisItems.push({
          questionId: k,
          selectedOptionIds: Array.isArray(v) ? v : [v]
        });
      }
    }
  }

  if (analysisItems.length === 0) {
    return {
      success: false,
      results: [],
      error: 'AI response did not contain an "analysis" array.'
    };
  }

  const validatedResults = [];

  for (const origQ of originalQuestions) {
    if (isPersonalOrAttendanceQuestion(origQ)) {
      validatedResults.push({
        questionId: origQ.id,
        index: origQ.index,
        title: origQ.title,
        type: origQ.type,
        needsUserInput: true,
        confidence: 'LOW',
        userPromptMessage: 'Personal identity or attendance verification question — requires your manual selection.',
        selectedOptionIds: [],
        selectedOptionLabels: [],
        reasoning: 'Blocked automatic selection: attendance and personal identity responses are never fabricated.'
      });
      continue;
    }

    const aiItem = analysisItems.find(
      item => item.questionId === origQ.id || item.id === origQ.id || item.index === origQ.index
    ) || null;

    if (!aiItem) {
      // If AI omitted a question in a multi-question batch, use smart fallback
      if (originalQuestions.length > 1) {
        validatedResults.push(buildSmartFallbackItem(origQ));
      } else {
        validatedResults.push({
          questionId: origQ.id,
          index: origQ.index,
          title: origQ.title,
          type: origQ.type,
          needsUserInput: true,
          confidence: 'LOW',
          userPromptMessage: 'AI could not automatically determine suitable options. Please select manually.',
          selectedOptionIds: [],
          selectedOptionLabels: [],
          reasoning: 'Not answered by AI model.'
        });
      }
      continue;
    }

    const needsUserInput = Boolean(aiItem.needsUserInput);
    const confidence = ['HIGH', 'MEDIUM', 'LOW'].includes(aiItem.confidence) ? aiItem.confidence : 'HIGH';
    const reasoning = (aiItem.reasoning || aiItem.reason)
      ? String(aiItem.reasoning || aiItem.reason).trim()
      : 'AI suggested suitable choice.';

    const validOptionIds = [];
    const validOptionLabels = [];

    const candidateIds = Array.isArray(aiItem.selectedOptionIds)
      ? aiItem.selectedOptionIds
      : (Array.isArray(aiItem.opts) ? aiItem.opts : []);

    const candidateLabels = Array.isArray(aiItem.selectedOptionLabels)
      ? aiItem.selectedOptionLabels
      : [];

    if (!needsUserInput) {
      for (const optId of candidateIds) {
        const matchingOpt = (origQ.options || []).find(
          o => o.id === optId || o.label.toLowerCase() === String(optId).toLowerCase()
        );
        if (matchingOpt && !validOptionIds.includes(matchingOpt.id)) {
          validOptionIds.push(matchingOpt.id);
          validOptionLabels.push(matchingOpt.label);
        }
      }

      if (validOptionIds.length === 0 && candidateLabels.length > 0) {
        for (const lbl of candidateLabels) {
          const matchingOpt = (origQ.options || []).find(
            o => o.label.toLowerCase() === String(lbl).toLowerCase()
          );
          if (matchingOpt && !validOptionIds.includes(matchingOpt.id)) {
            validOptionIds.push(matchingOpt.id);
            validOptionLabels.push(matchingOpt.label);
          }
        }
      }
    }

    if ((origQ.type === QUESTION_TYPES.RADIO || origQ.type === QUESTION_TYPES.LINEAR_SCALE) && validOptionIds.length > 1) {
      validOptionIds.splice(1);
      validOptionLabels.splice(1);
    }

    const effectiveNeedsInput = needsUserInput || validOptionIds.length === 0;

    validatedResults.push({
      questionId: origQ.id,
      index: origQ.index,
      title: origQ.title,
      type: origQ.type,
      needsUserInput: effectiveNeedsInput,
      confidence: effectiveNeedsInput ? 'LOW' : confidence,
      userPromptMessage: aiItem.userPromptMessage || (effectiveNeedsInput ? 'Please choose your preferred answer.' : ''),
      selectedOptionIds: validOptionIds,
      selectedOptionLabels: validOptionLabels,
      reasoning
    });
  }

  return {
    success: true,
    results: validatedResults
  };
}
