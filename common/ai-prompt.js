/**
 * Smart Form Tick Assistant - AI Prompt Generator & Response Sanitizer
 * Produces structured prompts for OpenRouter and extracts/validates JSON responses.
 *
 * Enforces strict safety rules:
 * - Never invent personal identification or fabricated attendance data.
 * - Handles survey/questionnaire scale & demographic questions seamlessly.
 * - Strips <think>...</think> blocks from reasoning models and salvages partial JSON.
 */

import { QUESTION_TYPES } from './constants.js';

// Patterns matching strict personal identity or attendance verification questions
const PERSONAL_OR_ATTENDANCE_PATTERNS = [
  /\b(mark\s+your\s+(lecture\s+)?attendance|present\s+in\s+class|mark\s+present|lecture\s+attendance|sign[\s-]?in\s+sheet)\b/i,
  /\b(student\s*id|roll\s*(no|number)|registration\s*(no|number)|matric\s*(no|number)|employee\s*id)\b/i,
  /\b(confirm\s+your\s+identity|identity\s+verification|verify\s+your\s+identity)\b/i,
  /\b(what\s+is\s+your\s+(full\s+)?name|your\s+(phone|mobile)\s+number|your\s+email\s+address|passport\s+number|national\s+id)\b/i
];

/**
 * Deterministically detects if a question asks for personal identity or attendance verification.
 * @param {object} question - Question object with title and description
 * @returns {boolean}
 */
export function isPersonalOrAttendanceQuestion(question) {
  if (!question) return false;
  const combinedText = `${question.title || ''} ${question.description || ''}`.trim();
  return PERSONAL_OR_ATTENDANCE_PATTERNS.some(pattern => pattern.test(combinedText));
}

/**
 * Selects a sensible, context-aware option for a question when an upstream free AI model
 * truncates or omits a response on a survey/questionnaire.
 * Respects strict anti-fabrication rules for personal identity and attendance.
 * @param {object} origQ
 * @returns {object}
 */
export function buildSmartFallbackItem(origQ) {
  if (isPersonalOrAttendanceQuestion(origQ)) {
    return {
      questionId: origQ.id,
      index: origQ.index,
      title: origQ.title,
      type: origQ.type,
      needsUserInput: true,
      confidence: 'LOW',
      userPromptMessage: 'Personal identity or attendance verification question — requires your manual selection.',
      selectedOptionIds: [],
      selectedOptionLabels: [],
      reasoning: 'Blocked automatic selection: attendance and personal identity responses are never fabricated.'
    };
  }

  const options = origQ.options || [];
  const normalOptions = options.filter(o => !o.isOther);
  const pool = normalOptions.length > 0 ? normalOptions : options;

  if (pool.length === 0) {
    return {
      questionId: origQ.id,
      index: origQ.index,
      title: origQ.title,
      type: origQ.type,
      needsUserInput: true,
      confidence: 'LOW',
      userPromptMessage: 'Please choose your preferred answer.',
      selectedOptionIds: [],
      selectedOptionLabels: [],
      reasoning: 'No selectable options found.'
    };
  }

  let chosen = null;

  // 1. Check for affirmative/consent option (e.g. "Agree", "Yes", "I agree")
  chosen = pool.find(o => /^(i\s+)?(strongly\s+)?(agree|yes|accept|understood|consent)\b/i.test(o.label.trim()) && !/disagree/i.test(o.label));

  // 2. Check for balanced Likert / frequency scale options (e.g. "Sometimes", "Rarely", "Some or a little", "Occasionally", "Neutral")
  if (!chosen) {
    chosen = pool.find(o => /\b(sometimes|some\s+or\s+a\s+little|occasionally|neutral|moderately|rarely)\b/i.test(o.label));
  }

  // 3. Otherwise pick a balanced option (middle option for 4-5 item scales, or first option)
  if (!chosen) {
    const idx = pool.length >= 4 ? Math.floor(pool.length / 2) - 1 : 0;
    chosen = pool[Math.max(0, idx)];
  }

  // IMPORTANT: This is a rule-based heuristic, NOT an AI answer. It is flagged so the
  // popup never auto-approves it and the user can see it was not generated by the model.
  return {
    questionId: origQ.id,
    index: origQ.index,
    title: origQ.title,
    type: origQ.type,
    needsUserInput: false,
    isFallback: true,
    confidence: 'LOW',
    userPromptMessage: '',
    selectedOptionIds: [chosen.id],
    selectedOptionLabels: [chosen.label],
    reasoning: 'Heuristic fallback (AI model did not respond) — review before applying.'
  };
}

/**
 * Generates smart fallback results for an entire batch of questions.
 * @param {Array<object>} questions
 * @returns {Array<object>}
 */
export function selectSmartFallbackForBatch(questions = []) {
  return questions.map(q => buildSmartFallbackItem(q));
}

